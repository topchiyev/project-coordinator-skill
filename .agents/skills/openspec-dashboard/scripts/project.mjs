import { lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, isAbsolute, join, relative, resolve, sep } from 'node:path';

export const outputMarker = '<!-- Generated by OpenSpec Dashboard Skill -->';
const outputMarkers = [
  Buffer.from(outputMarker),
  Buffer.from('<!-- Generated by Project Dashboard Skill -->')
];

export function isGeneratedDashboard(html) {
  return outputMarkers.some(marker => html.subarray(0, marker.length).equals(marker));
}

function isInside(directory, path) {
  const pathFromDirectory = relative(directory, path);
  return pathFromDirectory && pathFromDirectory !== '..'
    && !pathFromDirectory.startsWith(`..${sep}`) && !isAbsolute(pathFromDirectory);
}

export function resolveProject(projectRoot, outputPath) {
  const root = realpathSync(projectRoot);
  const openSpecPath = join(root, 'openspec');
  const source = lstatSync(openSpecPath, { throwIfNoEntry: false });
  if (!source?.isDirectory()) {
    throw new Error(`Expected an openspec/ directory in ${root}`);
  }

  const output = resolve(root, outputPath);
  if (isAbsolute(outputPath) || extname(output).toLowerCase() !== '.html' || !isInside(root, output)) {
    throw new Error('The output must be a repository-relative .html file.');
  }

  const parts = relative(root, output).split(sep);
  let path = root;
  for (const part of parts) {
    path = join(path, part);
    const entry = lstatSync(path, { throwIfNoEntry: false });
    if (!entry) break;
    if (path === output) {
      if (!entry.isFile() || !isGeneratedDashboard(readFileSync(path))) {
        throw new Error(`The output already exists and is not a generated dashboard: ${output}`);
      }
    } else if (!entry.isDirectory()) {
      throw new Error(`The output parent is not a real directory: ${path}`);
    }
  }

  return { name: basename(root), root, openSpecPath, output };
}

function readDirectory(path, optional = false) {
  const entry = lstatSync(path, { throwIfNoEntry: false });
  if (!entry && optional) return [];
  if (!entry?.isDirectory()) throw new Error(`Expected a directory at ${path}`);
  return readdirSync(path, { withFileTypes: true })
    .sort((first, second) => first.name.localeCompare(second.name, 'en'));
}

function readDocument(root, path) {
  return {
    path: relative(root, path).split(sep).join('/'),
    name: basename(path),
    markdown: readFileSync(path, 'utf8')
  };
}

function readGroupContents(project, directory, includeChangeDates) {
  const documents = [];
  const metadataPath = join(directory, '.openspec.yaml');
  let lastModified;
  let metadata;

  function visit(directory) {
    for (const entry of readDirectory(directory)) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        visit(path);
        continue;
      }
      if (!entry.isFile()) continue;

      if (extname(entry.name).toLowerCase() === '.md') {
        documents.push(readDocument(project.root, path));
      }
      if (!includeChangeDates || path === project.output) continue;

      try {
        const file = lstatSync(path, { throwIfNoEntry: false });
        if (!file?.isFile()) continue;
        if (Number.isFinite(file.mtimeMs) && file.mtimeMs > (lastModified ?? -Infinity)) {
          lastModified = file.mtimeMs;
        }
        if (path === metadataPath) metadata = readFileSync(path, 'utf8');
      } catch {
        // Dates are optional if a file's metadata cannot be read.
      }
    }
  }

  visit(directory);
  return { documents, lastModified, metadata };
}

function readGroups(project, directory, activeChanges = false) {
  return readDirectory(directory, true)
    .filter(entry => entry.isDirectory() && !(activeChanges && entry.name === 'archive'))
    .map(entry => {
      const path = join(directory, entry.name);
      return {
        name: entry.name,
        path: relative(project.root, path).split(sep).join('/'),
        ...readGroupContents(project, path, activeChanges)
      };
    });
}

export function readProject(project) {
  const changesPath = join(project.openSpecPath, 'changes');
  const specsPath = join(project.openSpecPath, 'specs');
  const overviewPath = join(project.openSpecPath, 'README.md');
  const overview = lstatSync(overviewPath, { throwIfNoEntry: false })?.isFile()
    ? readDocument(project.root, overviewPath)
    : null;

  const specificationGroups = readGroups(project, specsPath);
  const topLevelSpecifications = readDirectory(specsPath, true)
    .filter(entry => entry.isFile() && extname(entry.name).toLowerCase() === '.md')
    .map(entry => readDocument(project.root, join(specsPath, entry.name)));

  return {
    overview,
    specificationGroups,
    topLevelSpecifications,
    changes: readGroups(project, changesPath, true),
    archives: readGroups(project, join(changesPath, 'archive')).reverse()
  };
}

export function writeDashboard(output, html) {
  const directory = dirname(output);
  mkdirSync(directory, { recursive: true });
  const temporaryDirectory = mkdtempSync(join(directory, '.openspec-dashboard-'));
  try {
    const temporaryFile = join(temporaryDirectory, 'dashboard.html');
    writeFileSync(temporaryFile, html, { flag: 'wx' });
    renameSync(temporaryFile, output);
  } finally {
    rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}
